// Writes docs/languages.md, the table of the languages the extension has, from translations/provenance.json.
//
// Usage: node translations/tools/languages.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const TIERS = {
	1: 'Well-resourced languages: machine translation is generally reliable.',
	2: "Mid-resourced languages: usable, worth a native speaker's review.",
	3: 'Low-resource languages: the first to drop if a review finds the translation misleading.',
};
const ORIGINS = {
	human: 'written by a person',
	machine: 'generated by a language model, not reviewed by a speaker of the language',
	merged: "a person's work, completed by a language model where it was missing (see translations/comparison.md)",
};

/** The text of docs/languages.md for a provenance file. */
export function renderLanguages(provenance) {
	const entries = Object.entries(provenance.catalogues);
	const lines = [
		'# Languages',
		'',
		`The interface of the extension is translated into ${entries.length} languages. The translations come from two`,
		'kinds of work, and none of them has been reviewed by a speaker of the language unless it says "written by a person":',
		'',
		...Object.entries(ORIGINS).map(([origin, meaning]) => `- **${origin}**: ${meaning}.`),
		'',
		'The language of the user is chosen by the system, as `ll` or `ll_CC` (a locale such as `pt_BR`); a regional locale',
		'without a catalogue of its own uses the catalogue of its language (`es_MX` uses `es`).',
		'This file is generated from `translations/provenance.json` by `translations/tools/languages.mjs`.',
	];
	for (const tier of Object.keys(TIERS)) {
		const rows = entries
			.filter(([, entry]) => String(entry.tier) === tier)
			.sort(([, a], [, b]) => a.name.localeCompare(b.name, 'en'));
		lines.push(
			'',
			`## Tier ${tier}`,
			'',
			TIERS[tier],
			'',
			'| Language | Code | Origin | Notes |',
			'| --- | --- | --- | --- |',
		);
		for (const [code, entry] of rows) {
			lines.push(`| ${entry.name} | \`${code}\` | ${entry.origin} | ${entry.note ?? ''} |`);
		}
	}
	return lines.join('\n') + '\n';
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const provenance = JSON.parse(readFileSync(new URL('../provenance.json', import.meta.url), 'utf8'));
	writeFileSync(new URL('../../docs/languages.md', import.meta.url), renderLanguages(provenance));
	console.log('docs/languages.md written.');
}
